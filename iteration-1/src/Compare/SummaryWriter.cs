using System.Globalization;
using System.Text;
using EmberTrace;
using EmberTrace.Testing;

namespace Compare;

public sealed class SummaryWriter(DirectoryInfo summary, MatrixPoints points, double minPercent)
{
    public const double NoisePercent = 5;

    private static readonly CultureInfo Invariant = CultureInfo.InvariantCulture;

    public void Write(IReadOnlyList<TraceRun> runs)
    {
        summary.Create();
        var index = new StringBuilder();
        index.AppendLine("# Summary").AppendLine();
        index.AppendLine("Generated by `src/Compare` from the `.ember` traces. Track A baseline: `" + points.TrackABaseline + "`; Track B baseline: `" + MatrixPoints.TrackBBaseline + "` (Track B is library + runtime).").AppendLine();
        foreach (var group in runs.GroupBy(r => (r.Point.Track, r.Scenario)).OrderBy(g => g.Key.Track, StringComparer.Ordinal).ThenBy(g => g.Key.Scenario, StringComparer.Ordinal))
        {
            var stem = group.Key.Track == "B" ? $"trackb-{group.Key.Scenario}" : group.Key.Scenario;
            var baseline = points.BaselineFor(group.Key.Track);
            var byLabel = group.GroupBy(r => r.Point).OrderBy(g => g.Key.Order).ToDictionary(g => g.Key, g => g.ToList());
            var rows = Aggregate(byLabel);
            WriteCsv(Path.Combine(summary.FullName, stem + ".csv"), rows);
            WriteRunsCsv(Path.Combine(summary.FullName, stem + "-runs.csv"), byLabel);
            var representatives = byLabel.ToDictionary(p => p.Key, p => Representative(p.Value));
            var diffs = WriteDiffs(stem, baseline, representatives);
            WriteTraces(stem, representatives);
            WriteMarkdown(Path.Combine(summary.FullName, stem + ".md"), stem, baseline, byLabel.Keys.ToList(), rows, diffs);
            index.AppendLine($"- [{stem}]({stem}.md): {string.Join(", ", byLabel.Keys.Select(p => $"{p.Label} ({byLabel[p].Count} runs)"))}");
            Console.WriteLine($"[compare] {stem}: {rows.Count} rows, {byLabel.Count} points");
        }

        File.WriteAllText(Path.Combine(summary.FullName, "index.md"), index.ToString());
    }

    private static List<AggregateRow> Aggregate(Dictionary<PointInfo, List<TraceRun>> byLabel)
    {
        var rows = new List<AggregateRow>();
        foreach (var (point, pointRuns) in byLabel)
        {
            foreach (var id in pointRuns.SelectMany(r => r.Scopes.Keys).Distinct().Order())
            {
                var samples = pointRuns.Where(r => r.Scopes.ContainsKey(id)).Select(r => r.Scopes[id]).ToList();
                var allocations = samples.Where(s => s.AllocBytes.HasValue).Select(s => (double)s.AllocBytes!.Value).ToList();
                rows.Add(new AggregateRow(
                    point,
                    id,
                    samples[0].Name,
                    Median(samples.Select(s => s.Times.P50Ms)),
                    Median(samples.Select(s => s.Times.MeanMs)),
                    Median(samples.Select(s => s.Times.P95Ms)),
                    allocations.Count == 0 ? null : Median(allocations),
                    samples.Count));
            }
        }

        return rows;
    }

    private static void WriteCsv(string path, IEnumerable<AggregateRow> rows)
    {
        var text = new StringBuilder("label,epoch,scope,median_ms,mean_ms,p95_ms,alloc_bytes,n_runs\n");
        foreach (var row in rows)
        {
            text.Append(CultureInfo.InvariantCulture, $"{row.Point.Label},{row.Point.Epoch},{row.Scope},{Format(row.MedianMs)},{Format(row.MeanMs)},{Format(row.P95Ms)},{(row.AllocBytes is { } a ? Format(a) : "")},{row.Runs}\n");
        }

        File.WriteAllText(path, text.ToString());
    }

    private static void WriteRunsCsv(string path, Dictionary<PointInfo, List<TraceRun>> byLabel)
    {
        var text = new StringBuilder("label,epoch,track,round,scope,scope_id,pid,median_ms,mean_ms,p25_ms,p75_ms,p95_ms,total_ms,count,alloc_bytes\n");
        foreach (var (point, pointRuns) in byLabel)
        {
            foreach (var run in pointRuns)
            {
                foreach (var scope in run.Scopes.Values.OrderBy(s => s.Id))
                {
                    text.Append(CultureInfo.InvariantCulture, $"{point.Label},{point.Epoch},{point.Track},{run.Round},{scope.Name},{scope.Id},{run.Pid},{Format(scope.Times.P50Ms)},{Format(scope.Times.MeanMs)},{Format(scope.Times.P25Ms)},{Format(scope.Times.P75Ms)},{Format(scope.Times.P95Ms)},{Format(scope.Times.TotalMs)},{scope.Times.Count},{scope.AllocBytes?.ToString(Invariant) ?? ""}\n");
                }
            }
        }

        File.WriteAllText(path, text.ToString());
    }

    private Dictionary<PointInfo, string> WriteDiffs(string stem, string baseline, Dictionary<PointInfo, TraceRun> representatives)
    {
        var diffs = new Dictionary<PointInfo, string>();
        var reference = representatives.FirstOrDefault(p => p.Key.Label == baseline).Value;
        if (reference is null)
        {
            return diffs;
        }

        var directory = Directory.CreateDirectory(Path.Combine(summary.FullName, "diff", stem));
        foreach (var (point, run) in representatives)
        {
            if (point.Label == baseline)
            {
                continue;
            }

            var comparison = TraceDiff.Compare(reference.Stats, run.Stats);
            var text = TraceDiff.Format(comparison, run.Metadata, minPercent);
            diffs[point] = text;
            File.WriteAllText(Path.Combine(directory.FullName, $"{point.Label}-vs-{baseline}.txt"), text);
        }

        return diffs;
    }

    private void WriteTraces(string stem, Dictionary<PointInfo, TraceRun> representatives)
    {
        foreach (var (point, run) in representatives)
        {
            var directory = Directory.CreateDirectory(Path.Combine(summary.FullName, "traces", point.Label));
            var session = run.LoadSession();
            var processed = session.Process();
            var meta = session.Metadata;
            File.WriteAllText(Path.Combine(directory.FullName, stem + ".hotspots.txt"), TraceText.Write(processed, meta: meta, topHotspots: 20, maxDepth: 8));
            using (var folded = new StreamWriter(Path.Combine(directory.FullName, stem + ".folded")))
            {
                TraceText.WriteCollapsedStacks(processed, folded, meta);
            }

            using var chrome = File.Create(Path.Combine(directory.FullName, stem + ".chrome.json"));
            TraceExport.WriteChromeComplete(session, chrome, meta: meta);
        }
    }

    private static void WriteMarkdown(string path, string stem, string baseline, List<PointInfo> labels, List<AggregateRow> rows, Dictionary<PointInfo, string> diffs)
    {
        var text = new StringBuilder();
        text.AppendLine($"# {stem}").AppendLine();
        text.AppendLine($"Median over processes of the per-process median batch time (ms). Change is relative to `{baseline}`; changes under {NoisePercent.ToString(Invariant)}% are marked as noise (~). Runs per point: {string.Join(", ", labels.Select(l => $"{l.Label}={rows.Where(r => r.Point == l).Select(r => r.Runs).DefaultIfEmpty(0).Max()}"))}.").AppendLine();
        var scopes = rows.Select(r => (r.ScopeId, r.Scope)).Distinct().OrderBy(s => s.ScopeId).ToList();
        text.AppendLine("| scope | " + string.Join(" | ", labels.Select(l => $"{l.Label} ({l.Epoch})")) + " |");
        text.AppendLine("|---|" + string.Concat(labels.Select(_ => "---:|")));
        foreach (var (id, scope) in scopes)
        {
            var reference = rows.FirstOrDefault(r => r.ScopeId == id && r.Point.Label == baseline);
            var cells = labels.Select(label =>
            {
                var row = rows.FirstOrDefault(r => r.ScopeId == id && r.Point == label);
                if (row is null)
                {
                    return "–";
                }

                var value = row.MedianMs.ToString("0.0000", Invariant);
                if (reference is null || label.Label == baseline || reference.MedianMs <= 0)
                {
                    return value;
                }

                var change = (row.MedianMs - reference.MedianMs) / reference.MedianMs * 100;
                var marker = Math.Abs(change) < NoisePercent ? "~" : "";
                return $"{value} ({marker}{change.ToString("+0.0;-0.0;0.0", Invariant)}%)";
            });
            text.AppendLine($"| `{scope}` | " + string.Join(" | ", cells) + " |");
        }

        text.AppendLine().AppendLine("Allocated bytes per batch (median over processes of the per-process median):").AppendLine();
        text.AppendLine("| scope | " + string.Join(" | ", labels.Select(l => l.Label)) + " |");
        text.AppendLine("|---|" + string.Concat(labels.Select(_ => "---:|")));
        foreach (var (id, scope) in scopes)
        {
            var cells = labels.Select(label => rows.FirstOrDefault(r => r.ScopeId == id && r.Point == label)?.AllocBytes is { } bytes ? bytes.ToString("0", Invariant) : "–");
            text.AppendLine($"| `{scope}` | " + string.Join(" | ", cells) + " |");
        }

        foreach (var (point, diff) in diffs)
        {
            text.AppendLine().AppendLine($"## TraceDiff: {point.Label} vs {baseline} (representative runs)").AppendLine();
            text.AppendLine("```").AppendLine(diff.TrimEnd()).AppendLine("```");
        }

        File.WriteAllText(path, text.ToString());
    }

    private static TraceRun Representative(List<TraceRun> runs)
    {
        var ordered = runs.OrderBy(r => r.Scopes.Values.Sum(s => s.Times.P50Ms)).ToList();
        return ordered[(ordered.Count - 1) / 2];
    }

    private static double Median(IEnumerable<double> values)
    {
        var sorted = values.Order().ToArray();
        if (sorted.Length == 0)
        {
            return double.NaN;
        }

        var middle = sorted.Length / 2;
        return sorted.Length % 2 == 1 ? sorted[middle] : (sorted[middle - 1] + sorted[middle]) / 2;
    }

    private static string Format(double value) => value.ToString("R", Invariant);

    private sealed record AggregateRow(PointInfo Point, int ScopeId, string Scope, double MedianMs, double MeanMs, double P95Ms, double? AllocBytes, int Runs);
}
